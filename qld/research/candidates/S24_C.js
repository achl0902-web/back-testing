// S24 C (약점: 첫 하락 −8~−17% 미방어 — 2000·2018·2020·2021 같은 과열 고점 뒤 첫 하락):
// 최근 20거래일 안에 지수가 200일선보다 x 이상 위에 있었고(과열) 오늘 10일 수익률이 음수이면 이탈에 필요한 표를 1 낮춘다
// (보통 2→1, 복귀 후 보호기간 3→2). 매크로 이탈·복귀 조건은 챔피언 그대로.
// 근거: 200일선에서 멀리 벌어진 상태는 평균 회귀 압력이 크고 레버리지·추격 매수가 쌓여 있어, 첫 균열이 빠르고 깊다.
// 같은 1축이라도 과열 뒤 하락 중에 켜진 것은 정상 상승장의 1축보다 위험하다는 상태 조건부 문턱. 상방 변동성만 켜진 날은
// 10일 수익률 음수 조건으로 거른다. 챔피언 대체형이라 S09_lib.run(D, {exitVotes})로 만든다(플라시보는 훅만 이동).
const L = require('./S09_lib.js');
module.exports = (D, p) => {
  const x = p.x ?? 0.2, W = 20, n = D.n, ext = new Uint8Array(n);
  let last = -1e9;
  for (let j = 0; j < n; j++) {
    const m = D.ma[200][j];
    if (m > 0 && D.px[j] / m - 1 >= x) last = j;
    ext[j] = (j - last < W && D.r10[j] < 0) ? 1 : 0;
  }
  return L.run(D, { exitVotes: (j, need) => ext[j] ? need - 1 : need });
};
