// S25 B (금리 환경 분기 · 보호 기간, 약점: 2022형 실패 복귀 / IDEAS에 없는 '금리 국면별 규칙' 행):
// 2년물 금리가 252거래일 전보다 th%p 이상 높은 금리 인상 국면에서는 복귀 후 40거래일 보호기간의 3표 요구를 2표로 낮춘다
// (보호기간 밖 2표, 매크로, 복귀 조건은 챔피언 그대로). 이탈(복귀 직후 재이탈)에만 작용.
// 근거: S19 D(보호기간 일괄 축소 −2.0)는 상승장의 정상 눌림까지 재이탈시켜 손해였다. 보호기간이 지키는 것은 V자 회복 직후의
// 잔여 변동성인데, 긴축 국면의 약세장 반등(2022 3월·8월, 2000)은 할인율 상승이 계속돼 실패한다(S08: 2022형 복귀 실패는 금리형).
// 보호를 금리 인상 국면에서만 풀어 실패한 복귀를 빨리 정리하고, 인하·완화 국면(2003·2009·2020 회복)의 보호는 유지한다.
// DGS2(FRED, 일간, 발표 시차 1일). 챔피언 대체형: S09_lib.run(D, {exitVotes}).
const L = require('./S09_lib.js'), M = require('../lib/macro.js');
module.exports = (D, p) => {
  const th = p.th ?? 1.5, n = D.n, y = M.series(D, 'DGS2', 1), hike = new Uint8Array(n);
  for (let j = 252; j < n; j++) if (!isNaN(y[j]) && !isNaN(y[j - 252]) && y[j] - y[j - 252] >= th) hike[j] = 1;
  return L.run(D, { exitVotes: (j, need) => (hike[j] && need === 3) ? 2 : need });
};
